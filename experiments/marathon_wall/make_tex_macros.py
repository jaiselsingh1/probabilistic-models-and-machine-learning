"""Emit the analysis numbers as LaTeX macros.

Every figure quoted in the write-up is defined here from the artefacts the run
produced, so the prose cannot drift away from the fit.  Running the analysis
again and recompiling updates the text.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd


def _fmt(value: float, places: int = 2) -> str:
    if value is None or (isinstance(value, float) and not np.isfinite(value)):
        return r"\textit{n/a}"
    return f"{value:.{places}f}"


def _macro(name: str, body: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{body}}}"


def _read_csv(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def build(out_dir: Path) -> list[str]:
    lines: list[str] = ["% Generated by experiments/marathon_wall/make_tex_macros.py -- do not edit."]

    hygiene = _read_csv(out_dir / "hygiene.csv")
    metric = _read_csv(out_dir / "metric.csv")
    if hygiene is not None:
        lines.append(_macro("wallRawRows", f"{int(hygiene.groupby('race')['n_before'].max().sum()):,}"))
        lines.append(_macro("wallDropped", f"{int(hygiene['dropped'].sum()):,}"))
    if metric is not None:
        lines.append(_macro("wallN", f"{len(metric):,}"))
        lines.append(_macro("wallYMean", _fmt(float(metric['y'].mean()), 3)))
        lines.append(_macro("wallYSd", _fmt(float(metric['y'].std()), 3)))
        lines.append(_macro("wallYSkew", _fmt(float(metric['y'].skew()), 2)))
        lines.append(_macro("wallYRawSkew", _fmt(float(metric['y_raw'].skew()), 2)))

    compare = _read_csv(out_dir / "loo_compare.csv")
    if compare is not None:
        compare = compare.rename(columns={compare.columns[0]: "model"}).set_index("model")
        compare.index = compare.index.astype(str)
        lines.append(_macro("wallWinner", str(compare.index[0]).replace("_", " ")))
        for model, key in (("skewnormal", "Skew"), ("gaussian", "Gauss")):
            if model in compare.index:
                lines.append(_macro(f"wallDeltaElpd{key}", _fmt(float(compare.loc[model, "elpd_diff"]), 1)))
                lines.append(_macro(f"wallDseElpd{key}", _fmt(float(compare.loc[model, "dse"]), 1)))
                ratio = float(compare.loc[model, "elpd_diff"]) / max(float(compare.loc[model, "dse"]), 1e-9)
                lines.append(_macro(f"wallZElpd{key}", _fmt(ratio, 1)))

    loo = _read_csv(out_dir / "loo_table.csv")
    if loo is not None:
        best = loo.iloc[0]
        lines.append(_macro("wallPLoo", _fmt(float(best["p_loo"]), 1)))
        lines.append(_macro("wallMaxKhat", _fmt(float(best["max_khat"]), 2)))
        lines.append(_macro("wallFracKhat", _fmt(100.0 * float(best["frac_khat_gt_0.7"]), 2)))

    pi = _read_csv(out_dir / "pi_by_group.csv")
    if pi is not None:
        for _, row in pi.iterrows():
            tag = "".join(ch for ch in str(row["group"]) if ch.isalnum())
            lines.append(_macro(f"wallPi{tag}", f"{100 * float(row['pi_mean']):.0f}"))
            lines.append(_macro(f"wallPiLo{tag}", f"{100 * float(row['pi_lo']):.0f}"))
            lines.append(_macro(f"wallPiHi{tag}", f"{100 * float(row['pi_hi']):.0f}"))

    rule = _read_csv(out_dir / "decision_rule.csv")
    if rule is not None:
        for _, row in rule.iterrows():
            sex = str(row["sex"])
            lines.append(_macro(f"wallPiSex{sex}", f"{100 * float(row['pi_posterior_mean']):.0f}"))
            lines.append(_macro(f"wallRate{sex}", f"{100 * float(row['equal_cost_rate']):.0f}"))
            lines.append(_macro(f"wallSmyth{sex}", f"{100 * float(row['smyth_rate']):.0f}"))
            lines.append(_macro(f"wallLossRatio{sex}", _fmt(float(row["loss_ratio_matching_smyth"]), 1)))
            lines.append(_macro(f"wallBoundary{sex}", _fmt(float(row["decision_boundary_y"]), 3)))
            if "spurious_lower_boundary_y" in row:
                lines.append(_macro(f"wallLowBoundary{sex}", _fmt(float(row["spurious_lower_boundary_y"]), 3)))

    smyth = _read_csv(out_dir / "smyth_rule.csv")
    if smyth is not None:
        for _, row in smyth.iterrows():
            sex = str(row["sex"])
            lines.append(_macro(f"wallSmythHere{sex}", f"{100 * float(row['smyth_rule_rate_here']):.0f}"))
            lines.append(_macro(f"wallKappaAgree{sex}", _fmt(float(row["cohens_kappa"]), 2)))

    invariance = _read_csv(out_dir / "invariance.csv")
    if invariance is not None:
        lookup = {str(r["segment"]): float(r["smd"]) for _, r in invariance.iterrows()}
        for segment, name in (
            ("start->5k", "wallSmdFirstFive"),
            ("5k->10k", "wallSmdSecondFive"),
            ("25k->30k", "wallSmdTwentyFive"),
            ("40k->finish", "wallSmdFinish"),
        ):
            if segment in lookup:
                lines.append(_macro(name, _fmt(lookup[segment], 2)))

    early = _read_csv(out_dir / "early_shape.csv")
    if early is not None and len(early):
        lines.append(_macro("wallEarlyShapeSmd", _fmt(float(early.iloc[0]["smd"]), 2)))

    null = _read_csv(out_dir / "sim_skewnormal_null.csv")
    if null is not None and len(null):
        # az.compare returns rows ranked best-first; whichever name is in the
        # first row won on data generated with no mixture in it at all.
        name_column = "model" if "model" in null.columns else str(null.columns[0])
        ranked = null[name_column].astype(str).tolist()
        pretty = {"skewnormal": "the skew-normal", "mixture": "the mixture", "gaussian": "the Gaussian"}
        lines.append(_macro("wallNullWinner", pretty.get(ranked[0], ranked[0])))
        runner_up = null.iloc[1] if len(null) > 1 else None
        if runner_up is not None and "elpd_diff" in null.columns:
            lines.append(_macro("wallNullDelta", _fmt(float(runner_up["elpd_diff"]), 1)))
            if "dse" in null.columns:
                lines.append(_macro("wallNullDse", _fmt(float(runner_up["dse"]), 1)))

    shock = _read_csv(out_dir / "sim_year_shock.csv")
    if shock is not None and len(shock):
        lines.append(_macro("wallShockCovered", f"{int(shock['covered'].sum())}/{len(shock)}"))
        worst = float(np.max(np.abs(shock["pi_mean"] - shock["pi_true"])))
        lines.append(_macro("wallShockMaxErr", _fmt(100 * worst, 1)))
        hot = shock.loc[shock["pi_true"].idxmax()]
        lines.append(_macro("wallShockHotTrue", f"{100 * float(hot['pi_true']):.0f}"))
        lines.append(_macro("wallShockHotEst", f"{100 * float(hot['pi_mean']):.0f}"))

    cp = _read_csv(out_dir / "changepoint_summary.csv")
    if cp is not None and len(cp):
        values = {str(r["statistic"]): float(r["value"]) for _, r in cp.iterrows()}
        for key, name in (
            ("kappa_q10", "wallKappaLo"),
            ("kappa_q50", "wallKappaMed"),
            ("kappa_q90", "wallKappaHi"),
        ):
            if key in values:
                lines.append(_macro(name, _fmt(values[key], 1)))
    return lines


# Every macro the write-up references.  Any that the artefacts did not supply is
# given a visible placeholder so the document still compiles and the gap is
# obvious in the PDF rather than silent.
EXPECTED: tuple[str, ...] = (
    "wallRawRows", "wallDropped", "wallN", "wallYMean", "wallYSd", "wallYSkew", "wallYRawSkew",
    "wallWinner", "wallDeltaElpdSkew", "wallDseElpdSkew", "wallZElpdSkew",
    "wallDeltaElpdGauss", "wallDseElpdGauss", "wallZElpdGauss",
    "wallPLoo", "wallMaxKhat", "wallFracKhat",
    "wallPiSexM", "wallPiSexF", "wallRateM", "wallRateF", "wallSmythM", "wallSmythF",
    "wallLossRatioM", "wallLossRatioF", "wallBoundaryM", "wallBoundaryF",
    "wallLowBoundaryM", "wallLowBoundaryF",
    "wallSmdFirstFive", "wallSmdSecondFive", "wallSmdTwentyFive", "wallSmdFinish",
    "wallEarlyShapeSmd", "wallNullWinner", "wallNullDelta", "wallNullDse",
    "wallShockCovered", "wallShockMaxErr", "wallShockHotTrue", "wallShockHotEst",
    "wallKappaLo", "wallKappaMed", "wallKappaHi",
    "wallSmythHereM", "wallSmythHereF", "wallKappaAgreeM", "wallKappaAgreeF",
)


def with_fallbacks(lines: list[str]) -> list[str]:
    """Append a \\providecommand placeholder for every macro still undefined."""
    defined = {line.split("{\\", 1)[1].split("}", 1)[0] for line in lines if line.startswith("\\newcommand")}
    tail = [f"\\providecommand{{\\{name}}}{{\\textbf{{??}}}}" for name in EXPECTED if name not in defined]
    return lines + ([""] + tail if tail else [])


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--tex", type=Path, required=True)
    args = parser.parse_args(argv)
    lines = with_fallbacks(build(args.out_dir))
    args.tex.write_text("\n".join(lines) + "\n")
    missing = sum(1 for line in lines if line.startswith("\\providecommand"))
    print(f"wrote {len(lines) - 1} macro lines to {args.tex} ({missing} still placeholders)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
