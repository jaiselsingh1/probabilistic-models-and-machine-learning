"""HW2 Q2: the specified Monte Carlo grid search and reproducible figures.

Run: python q2_kl.py
Every grid point receives 10,000 newly drawn samples (no shared random numbers).
Quadrature checks the selected point; it does not choose or replace the MC fit.
"""

from pathlib import Path
import csv
import json
import math
import os

ROOT = Path(__file__).resolve().parent
os.environ.setdefault("MPLCONFIGDIR", str(ROOT / ".mpl-cache"))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.integrate import quad
from scipy.special import logsumexp
from scipy.stats import norm

SEED = 20261111
N_SAMPLES = 10_000
A, S = 3.0, 1.0


def log_target(z, a=A, s=S):
    z = np.asarray(z)
    return logsumexp(np.stack([norm.logpdf(z, -a, s), norm.logpdf(z, a, s)]), axis=0) - np.log(2)


def reverse_kl_quad(m, sigma, a=A, s=S):
    # Independent algebraic form of log p: log cosh is evaluated stably.
    def integrand(eps):
        z = m + sigma * eps
        t = a * z / s**2
        log_cosh = np.logaddexp(t, -t) - np.log(2)
        log_ratio = np.log(s / sigma) - 0.5 * eps**2 + (z*z + a*a) / (2*s*s) - log_cosh
        return norm.pdf(eps) * log_ratio
    # Normal tails beyond +/-12 are negligible at this scale.
    return quad(integrand, -12, 12, epsabs=2e-11, epsrel=2e-11, limit=200)


def main():
    out, figures = ROOT / "results", ROOT / "figures"
    out.mkdir(exist_ok=True)
    figures.mkdir(exist_ok=True)
    means = np.arange(-40, 41, dtype=float) / 10
    sigmas = np.arange(5, 41, dtype=float) / 10
    estimates = np.empty((len(sigmas), len(means)))
    errors = np.empty_like(estimates)
    rng = np.random.default_rng(SEED)
    for im, m in enumerate(means):
        for js, sigma in enumerate(sigmas):
            eps = rng.standard_normal(N_SAMPLES)
            z = m + sigma * eps
            log_q = -0.5 * eps**2 - np.log(sigma) - 0.5 * np.log(2*np.pi)
            ratios = log_q - log_target(z)
            estimates[js, im] = ratios.mean()
            errors[js, im] = ratios.std(ddof=1) / np.sqrt(N_SAMPLES)

    js, im = np.unravel_index(np.argmin(estimates), estimates.shape)
    best_m, best_s = float(means[im]), float(sigmas[js])
    quad_value, quad_error = reverse_kl_quad(best_m, best_s)
    mirror_value, _ = reverse_kl_quad(-best_m, best_s)
    forward_m, forward_s = 0.0, math.sqrt(A*A + S*S)
    reverse_at_forward, _ = reverse_kl_quad(forward_m, forward_s)

    # Checks of normalization, symmetry, and the two stable log-density formulas.
    probes = np.linspace(-100, 100, 2001)
    alt = -np.log(S) - 0.5*np.log(2*np.pi) - (probes**2+A*A)/(2*S*S) + np.logaddexp(A*probes/S**2, -A*probes/S**2) - np.log(2)
    np.testing.assert_allclose(log_target(probes), alt, atol=2e-12, rtol=1e-13)
    assert np.isfinite(estimates).all() and estimates.shape == (36, 81)
    np.testing.assert_allclose(quad_value, mirror_value, atol=1e-12)
    mass, _ = quad(lambda z: float(np.exp(log_target(z))), -20, 20, epsabs=1e-12)
    np.testing.assert_allclose(mass, 1, atol=1e-12)

    with (out / "q2_grid.csv").open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["m", "sigma", "kl_mc", "mc_se", "n_samples"])
        for i, m in enumerate(means):
            for j, sigma in enumerate(sigmas):
                writer.writerow([m, sigma, estimates[j, i], errors[j, i], N_SAMPLES])

    result = {
        "seed": SEED, "rng": "numpy.random.default_rng / PCG64",
        "grid_order": "m increasing outer loop, sigma increasing inner loop",
        "n_samples_per_grid_point": N_SAMPLES, "grid_points": estimates.size,
        "m_range_step": [-4, 4, 0.1], "sigma_range_step": [0.5, 4, 0.1],
        "target_a": A, "target_s": S,
        "forward": {"m": forward_m, "sigma": forward_s},
        "reverse_mc_selected": {"m": best_m, "sigma": best_s,
            "kl_estimate": float(estimates[js, im]), "pointwise_mc_se": float(errors[js, im]),
            "kl_quadrature": quad_value, "quadrature_absolute_error": quad_error},
        "reverse_kl_at_forward": reverse_at_forward,
        "checks": "passed",
        "versions": {"numpy": np.__version__, "matplotlib": matplotlib.__version__},
    }
    (out / "q2_results.json").write_text(json.dumps(result, indent=2) + "\n")
    macros = {
        "klSeed": str(SEED), "klGridN": str(estimates.size),
        "klBestM": f"{best_m:.1f}", "klBestSigma": f"{best_s:.1f}",
        "klBestMC": f"{estimates[js, im]:.5f}", "klBestSE": f"{errors[js, im]:.5f}",
        "klBestQuad": f"{quad_value:.5f}", "klForwardSigma": f"{forward_s:.5f}",
        "klReverseAtForward": f"{reverse_at_forward:.4f}",
    }
    (figures / "q2_numbers.tex").write_text("% Generated by q2_kl.py; do not edit.\n" + "".join(
        f"\\newcommand{{\\{key}}}{{{value}}}\n" for key, value in macros.items()))

    plt.rcParams.update({"font.family": "serif", "font.size": 10,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "pdf.fonttype": 42, "savefig.bbox": "tight"})
    fig, ax = plt.subplots(figsize=(6.5, 3.25), layout="constrained")
    mesh = ax.pcolormesh(means, sigmas, estimates, shading="nearest", cmap="viridis",
                         rasterized=True)  # avoids hairline seams between cells in PDF viewers
    fig.colorbar(mesh, ax=ax, label=r"Estimated $\mathrm{KL}(q\Vert p)$ (nats)")
    ax.scatter(best_m, best_s, marker="*", s=145, color="#ef6c00", edgecolor="white", linewidth=0.6,
               label=fr"MC minimum $({best_m:.1f},\,{best_s:.1f})$", zorder=3)
    ax.scatter(forward_m, forward_s, marker="D", s=45, facecolor="white", edgecolor="#222222",
               label=r"Forward KL fit $(0,\sqrt{10})$", zorder=3)
    ax.set(xlabel=r"Gaussian mean $m$", ylabel=r"Gaussian standard deviation $\sigma$",
           xlim=(-4.05, 4.05), ylim=(0.45, 4.05))
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.01), ncol=2, frameon=False, fontsize=8)
    fig.savefig(figures / "q2_heatmap.pdf", dpi=300)
    plt.close(fig)

    z = np.linspace(-8, 8, 1601)
    fig, ax = plt.subplots(figsize=(6.5, 3.1), layout="constrained")
    ax.plot(z, np.exp(log_target(z)), color="#222222", lw=2, label=r"Target $p$: equal Gaussian mixture")
    ax.plot(z, norm.pdf(z, forward_m, forward_s), color="#166a9b", lw=1.8, ls="--",
            label=r"Forward KL: $\mathcal{N}(0,10)$")
    ax.plot(z, norm.pdf(z, best_m, best_s), color="#bc4c19", lw=1.8, ls="-.",
            label=fr"Reverse KL grid fit: $\mathcal{{N}}({best_m:.1f}, {best_s**2:.2f})$")
    ax.set(xlabel=r"$z$", ylabel="Probability density", xlim=(-8, 8), ylim=(0, .44))
    ax.legend(loc="upper left", fontsize=8, framealpha=0.97)
    fig.savefig(figures / "q2_densities.pdf")
    plt.close(fig)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
