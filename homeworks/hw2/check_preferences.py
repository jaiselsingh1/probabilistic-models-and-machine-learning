"""Reproduce the fixed nine-of-ten preference example in HW2, Question 3(a)."""

import json
from pathlib import Path

import numpy as np
from scipy.integrate import quad
from scipy.special import expit, logit, ndtr, roots_legendre

ROOT = Path(__file__).resolve().parent
SLOPE_LIMIT = 1.5
TOLERABLE_REGRET = 0.1
WINS, LOSSES = 9, 1


def likelihood(theta):
    # Curvature cancels in U(+1) - U(-1) = 2 theta.
    return expit(2 * theta) ** WINS * expit(-2 * theta) ** LOSSES


def conditional_good(theta, curvature_sd):
    # Regret of +1 is max(0, -2 theta, -theta - curvature).
    # Integrals for this event start at theta >= -TOLERABLE_REGRET / 2.
    if curvature_sd == 0:
        return np.ones_like(theta)
    return ndtr((theta + TOLERABLE_REGRET) / curvature_sd)


def main():
    lower, upper = -SLOPE_LIMIT, SLOPE_LIMIT
    good_from = -TOLERABLE_REGRET / 2
    normalizer = quad(likelihood, lower, upper, epsabs=1e-14)[0]

    # Independent check: with p = sigmoid(2 theta), the uniform slope prior
    # contributes a Jacobian 1/[2p(1-p)]. The posterior density in p is
    # proportional to p^8 for nine wins and one loss on the truncated support.
    p_lo, p_good, p_hi = expit(2 * np.array([lower, good_from, upper]))
    p_normalizer = (p_hi ** WINS - p_lo ** WINS) / WINS
    nodes, weights = roots_legendre(96)
    p = (p_good + p_hi + (p_hi - p_good) * nodes) / 2
    theta = logit(p) / 2
    p_weights = (p_hi - p_good) * weights * p ** (WINS - 1) / (2 * p_normalizer)

    probabilities = {}
    errors = []
    for model, sd in (("linear", 0), ("curvature_sd_one", 1), ("curvature_sd_half", 0.5)):
        integral = quad(lambda t: likelihood(t) * conditional_good(t, sd),
                        good_from, upper, epsabs=1e-14)[0]
        probability = integral / normalizer
        transformed = np.dot(p_weights, conditional_good(theta, sd))
        np.testing.assert_allclose(transformed, probability, rtol=0, atol=1e-12)
        probabilities[model] = float(probability)
        errors.append(abs(transformed - probability))

    # With a unit-temperature logistic choice, I_d(theta) for a feature gap d
    # is d^2 / [4 cosh^2(d theta/2)]. I_2 > I_1 iff 2c > 2c^2 - 1, where
    # c = cosh(theta/2), equivalently |theta| < the boundary below. Hence this
    # ordering also holds for posterior-expected Fisher information.
    fisher_boundary = 2 * np.arccosh((1 + np.sqrt(3)) / 2)
    assert SLOPE_LIMIT < fisher_boundary
    z = np.array([-1, 0, 1])
    true_utility = z - 2 * z**2
    true_regret = int(true_utility.max() - true_utility[2])
    posterior_prediction = quad(lambda t: likelihood(t) * expit(t),
                                lower, upper, epsabs=1e-14)[0] / normalizer
    diagnostic = {
        "truth": float(expit(true_utility[2] - true_utility[1])),
        "linear_at_theta_one": float(expit(1)),
        "linear_posterior_predictive": float(posterior_prediction),
    }
    report = {
        "slope_prior_bounds": [lower, upper], "outer_pair_wins": WINS,
        "outer_pair_losses": LOSSES, "regret_tolerance": TOLERABLE_REGRET,
        "probability_plus_one_within_tolerance": probabilities,
        "largest_quadrature_discrepancy": float(max(errors)),
        "fisher_equal_information_abs_theta": float(fisher_boundary),
        "probability_plus_one_preferred_to_zero": diagnostic,
        "true_regret_of_plus_one": true_regret,
    }
    macros = {
        "prefLinearPct": f"{100 * probabilities['linear']:.1f}",
        "prefWidePct": f"{100 * probabilities['curvature_sd_one']:.1f}",
        "prefNarrowPct": f"{100 * probabilities['curvature_sd_half']:.1f}",
        "prefDiagnosticTruth": f"{diagnostic['truth']:.2f}",
        "prefDiagnosticAtOne": f"{diagnostic['linear_at_theta_one']:.2f}",
        "prefDiagnosticPosterior": f"{posterior_prediction:.2f}",
        "prefTrueRegret": str(true_regret),
    }
    for directory in ("figures", "results"):
        (ROOT / directory).mkdir(exist_ok=True)
    (ROOT / "figures/q3_numbers.tex").write_text(
        "% Generated by check_preferences.py.\n"
        + "".join(f"\\newcommand{{\\{name}}}{{{value}}}\n" for name, value in macros.items())
    )
    output = json.dumps(report, indent=2) + "\n"
    (ROOT / "results/q3_checks.json").write_text(output)
    print(output, end="")


if __name__ == "__main__":
    main()
